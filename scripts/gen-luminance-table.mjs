// Generates crates/core/src/luminance.rs from the pinned upstream reference.
//
// `getLuminance()` feeds Math.pow only integer channel values 0..=255 (its
// input comes from toRgb(), which rounds). That makes the sRGB linearisation
// a 256-entry pure function, so we tabulate V8's exact results instead of
// re-deriving them with a libm whose last bit differs per target.
import { writeFileSync } from "node:fs";

const bits = (x) => {
  const b = Buffer.alloc(8);
  b.writeDoubleLE(x);
  return b.readBigUInt64LE();
};

let out = `//! Generated by scripts/gen-luminance-table.mjs. Do not edit by hand.
//!
//! sRGB linearisation of the 256 possible integer channel values, captured as
//! raw f64 bit patterns from V8 (the reference implementation's runtime).
//!
//! Rationale (DECISIONS.md D-012): \`Math.pow(x, 2.4)\` is not bit-identical
//! across libm implementations. Rust's std \`powf\` on macOS matches V8 for
//! 207/256 inputs and the wasm32 target's MUSL-derived \`pow\` for 225/256 —
//! a 1-ULP spread that upstream's \`readability\` test detects via exact
//! equality. Tabulating removes the dependency on any libm and makes the port
//! bit-exact on every target.

pub static SRGB_LINEAR: [u64; 256] = [
`;

for (let c = 0; c < 256; c++) {
  const s = c / 255;
  const v = s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  out += `    0x${bits(v).toString(16).padStart(16, "0")}, // ${c} -> ${v}\n`;
}
out += `];

/// sRGB linearisation for an integer channel value.
///
/// Returns \`None\` for inputs outside the tabulated domain so the caller can
/// fall back to computing the value directly; upstream can only produce
/// integers in 0..=255 here, so that path is unreachable in practice.
pub fn srgb_linear(channel: f64) -> Option<f64> {
    if channel.fract() != 0.0 || !(0.0..=255.0).contains(&channel) {
        return None;
    }
    Some(f64::from_bits(SRGB_LINEAR[channel as usize]))
}
`;

writeFileSync("crates/core/src/luminance.rs", out);
console.log("wrote crates/core/src/luminance.rs (256 entries)");
